//! Fixes for frontend defaults that fight a clean library.
//!
//! ES-DE lists `.bin` for every system that takes cue sheets, so each cue's track files show up
//! as games of their own beside it. On those systems a `.bin` is always a cue sheet's track
//! (the library rule is `scan::is_cue_system`; lone ones are library problems, from
//! `scan::lone_bins`). The fix is ES-DE's own entry for the system, minus `.bin`, in the
//! machine's ES-DE `custom_systems/es_systems.xml` (an entry there replaces the built-in one of
//! the same name).

use std::collections::HashMap;
use std::path::PathBuf;

use anyhow::{Result, bail};

use crate::platforms;
use crate::scan::{self, EntryKind, Game};
use crate::settings::Settings;

const CUE_SYSTEMS: &str = include_str!("../assets/esde_cue_systems.xml");

/// Marks files RomServer wrote, so it never overwrites or removes one a person made.
pub const MARKER: &str = "Generated by RomServer";

/// ES-DE's entries for the systems listing both `.cue` and `.bin`: name → entry text.
fn cue_system_entries() -> HashMap<&'static str, &'static str> {
    let mut out = HashMap::new();
    let mut rest = CUE_SYSTEMS;
    while let Some(start) = rest.find("<system>") {
        let Some(len) = rest[start..].find("</system>") else {
            break;
        };
        let entry = &rest[start..start + len + "</system>".len()];
        if let Some(name) = entry
            .split_once("<name>")
            .and_then(|(_, r)| r.split_once("</name>"))
            .map(|(n, _)| n.trim())
        {
            out.insert(name, entry);
        }
        rest = &rest[start + len..];
    }
    out
}

/// What the fix would do for one machine. Nothing is written anywhere: the user either fixes
/// ES-DE by hand from this, or gives RomServer their custom systems file to fix (`apply`).
#[derive(Debug, Default)]
pub struct EsdeBinFix {
    /// Systems that need it, with how many cue track files ES-DE lists as games there.
    pub fixed: Vec<(String, usize)>,
    /// `.bin` files without a cue sheet, per system: ES-DE stops listing them after the fix.
    pub lone_bins: Vec<(String, Vec<PathBuf>)>,
    /// Where ES-DE's custom systems file is on the machine.
    pub path: Option<PathBuf>,
    /// ES-DE's own entry for each system that needs it, without `.bin`.
    entries: Vec<(String, String)>,
}

impl EsdeBinFix {
    pub fn is_needed(&self) -> bool {
        !self.entries.is_empty()
    }

    /// The user's custom systems file with the fix applied. Empty input means they have none:
    /// RomServer's default file. Their own entries are kept as they are; for a system they have
    /// customised, only `.bin` is taken out of its extensions.
    pub fn apply(&self, existing: &str, node_name: &str) -> Result<String> {
        if existing.trim().is_empty() {
            return Ok(format!(
                "<?xml version=\"1.0\"?>\n\
                 <!-- {MARKER} for {node_name}. ES-DE's own entries for these systems, without\n     \
                 .bin: every .bin in their folders is a cue sheet's track, which ES-DE would\n     \
                 otherwise list as a game of its own. -->\n\
                 <systemList>\n    {}\n</systemList>\n",
                self.entries
                    .iter()
                    .map(|(_, e)| e.as_str())
                    .collect::<Vec<_>>()
                    .join("\n    ")
            ));
        }
        let Some(close) = existing.rfind("</systemList>") else {
            bail!("that doesn't look like an ES-DE systems file (no </systemList>)");
        };
        if !existing.contains("<systemList") {
            bail!("that doesn't look like an ES-DE systems file (no <systemList>)");
        }
        let mut text = existing[..close].to_string();
        let mut added = Vec::new();
        for (system, entry) in &self.entries {
            match find_system(&text, system) {
                // Theirs: keep it, only drop .bin from its extensions.
                Some((start, end)) => {
                    let fixed = without_bin(&text[start..end]);
                    text.replace_range(start..end, &fixed);
                }
                None => added.push(format!(
                    "    <!-- {system}: added by RomServer, ES-DE's entry without .bin -->\n    {entry}\n"
                )),
            }
        }
        for a in added {
            text.push_str(&a);
        }
        text.push_str(&existing[close..]);
        Ok(text)
    }
}

/// Byte range of the `<system>` entry named `name` in a systems file, if there is one.
fn find_system(text: &str, name: &str) -> Option<(usize, usize)> {
    let mut from = 0;
    while let Some(rel) = text[from..].find("<system>") {
        let start = from + rel;
        let end = start + text[start..].find("</system>")? + "</system>".len();
        let entry = &text[start..end];
        let entry_name = entry
            .split_once("<name>")
            .and_then(|(_, r)| r.split_once("</name>"))
            .map(|(n, _)| n.trim());
        if entry_name == Some(name) {
            return Some((start, end));
        }
        from = end;
    }
    None
}

/// An entry with `.bin` taken out of its `<extension>` list; everything else untouched.
fn without_bin(entry: &str) -> String {
    let Some((before, rest)) = entry.split_once("<extension>") else {
        return entry.to_string();
    };
    let Some((list, after)) = rest.split_once("</extension>") else {
        return entry.to_string();
    };
    let kept: Vec<&str> = list
        .split_whitespace()
        .filter(|t| !t.eq_ignore_ascii_case(".bin"))
        .collect();
    format!("{before}<extension>{}</extension>{after}", kept.join(" "))
}

/// Works out the `.bin` fix for a machine's ES-DE, from its systems' real folders.
pub fn esde_bin_fix(settings: &Settings, node_name: &str) -> Result<EsdeBinFix> {
    let node = settings.node(node_name)?;
    let platforms = platforms::bundled();
    let platform = platforms.platform(&node.platform)?;
    let mut fix = EsdeBinFix::default();
    let Some(dir) = &platform.esde_custom_systems else {
        return Ok(fix);
    };
    let layout = platforms.layout(platform);
    let entries = cue_system_entries();
    for system in settings.node_systems(node) {
        let Some(entry) = entries.get(system) else {
            continue;
        };
        let scan = scan::scan_system(&settings.system_root(system)?)?;
        let mut tracks = 0;
        for game in &scan.games {
            let entries: Vec<&scan::Entry> = match game {
                Game::Single { entry, .. } => vec![entry],
                Game::MultiDisc { discs, .. } => discs.iter().collect(),
            };
            tracks += entries
                .iter()
                .filter(|e| e.kind == EntryKind::CueSheet)
                .map(|e| e.tracks.len())
                .sum::<usize>();
        }
        let lone = scan::lone_bins(&scan);
        if tracks == 0 && lone.is_empty() {
            continue;
        }
        if !lone.is_empty() {
            fix.lone_bins.push((system.to_string(), lone));
        }
        let folder = layout.folder(system);
        let entry = without_bin(entry).replace(
            &format!("%ROMPATH%/{system}<"),
            &format!("%ROMPATH%/{folder}<"),
        );
        fix.entries.push((system.to_string(), entry));
        fix.fixed.push((system.to_string(), tracks));
    }
    let home = node.home.as_deref().unwrap_or(&platform.default_home);
    let base = node.base.as_deref().unwrap_or(&platform.base);
    fix.path = Some(platforms::expand(dir, home, base).join("es_systems.xml"));
    Ok(fix)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bundled_entries_cover_the_cue_systems() {
        let entries = cue_system_entries();
        assert_eq!(entries.len(), 19, "{:?}", entries.keys());
        assert!(entries["psx"].contains(".bin .BIN"));
        assert!(entries["genesis"].contains("<name>genesis</name>"));
        // Both come from the same ES-DE lists, so the library rule and the fix cover the same
        // systems.
        let flagged: Vec<String> = crate::emulators::bundled()
            .unwrap()
            .systems
            .into_iter()
            .filter(|s| s.bin_is_cue_track)
            .map(|s| s.id)
            .collect();
        assert_eq!(flagged.len(), entries.len(), "{flagged:?}");
        assert!(flagged.iter().all(|s| entries.contains_key(s.as_str())));
        assert!(scan::is_cue_system("psx") && !scan::is_cue_system("snes"));
    }

    fn write(path: &std::path::Path, body: &str) {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, body).unwrap();
    }

    #[test]
    fn only_systems_whose_bins_are_all_cue_tracks_are_fixed() {
        let tmp = tempfile::tempdir().unwrap();
        let root = tmp.path();
        // PSX: every .bin belongs to a cue sheet.
        write(
            &root.join("PSX/Game (USA).cue"),
            "FILE \"Game (USA).bin\" BINARY\n",
        );
        write(&root.join("PSX/Game (USA).bin"), "data");
        // A legacy Genesis dump with a .bin cart (the standard is .md): unsupported, reported.
        write(&root.join("Genesis/Sonic (USA).bin"), "cart");
        write(&root.join("Genesis/Streets of Rage (USA).md"), "cart");
        let mut settings: Settings = toml::from_str(&format!(
            "library_root = \"{r}\"\nviews_root = \"{r}/views\"\ndatabase = \"{r}/db\"\n\
             [systems]\npsx = {{ folder = \"PSX\" }}\ngenesis = {{ folder = \"Genesis\" }}\n\
             [uses]\npsx = [\"ra-mednafen_psx\"]\ngenesis = [\"ra-genesis_plus_gx\"]\n",
            r = root.display()
        ))
        .unwrap();
        let mut node = crate::settings::Node::new("es-de", Default::default());
        node.home = Some("/home/deus".into());
        node.uses = settings.uses.clone();
        settings.nodes.insert("desk".into(), node);

        let fix = esde_bin_fix(&settings, "desk").unwrap();
        // Genesis gets the fix too: a .bin there is a legacy dump, reported, not a game.
        assert_eq!(
            fix.fixed,
            [("genesis".to_string(), 0), ("psx".to_string(), 1)]
        );
        assert_eq!(
            fix.lone_bins,
            [(
                "genesis".to_string(),
                vec![PathBuf::from("Sonic (USA).bin")]
            )]
        );
        assert_eq!(
            fix.path,
            Some(PathBuf::from(
                "/home/deus/ES-DE/custom_systems/es_systems.xml"
            ))
        );

        // No custom systems file yet: RomServer's default.
        let fresh = fix.apply("", "desk").unwrap();
        assert!(fresh.contains(MARKER));
        assert!(fresh.contains("<name>psx</name>") && fresh.contains("<name>genesis</name>"));
        for ext in fresh.lines().filter(|l| l.contains("<extension>")) {
            assert!(!ext.to_lowercase().contains(".bin"), "{ext}");
        }
        let psx = &fresh[fresh.find("<name>psx</name>").unwrap()..];
        let ext = psx.lines().find(|l| l.contains("<extension>")).unwrap();
        assert!(
            ext.contains(".cue") && ext.contains(".m3u") && ext.contains(".chd"),
            "{ext}"
        );

        // Their own file: other systems kept verbatim, PSX added.
        let theirs = "<?xml version=\"1.0\"?>\n<systemList>\n    <system>\n        \
                      <name>mygames</name>\n        <extension>.bin .sh</extension>\n    \
                      </system>\n</systemList>\n";
        let merged = fix.apply(theirs, "desk").unwrap();
        assert!(
            merged.contains("<extension>.bin .sh</extension>"),
            "theirs untouched"
        );
        assert!(merged.contains("<name>psx</name>") && merged.ends_with("</systemList>\n"));

        // Their own PSX entry: kept, only .bin taken out.
        let custom_psx = "<systemList>\n<system><name>psx</name><fullname>Mine</fullname>\
                          <extension>.bin .BIN .cue .m3u</extension></system>\n</systemList>";
        let merged = fix.apply(custom_psx, "desk").unwrap();
        assert!(merged.contains("<fullname>Mine</fullname><extension>.cue .m3u</extension>"));
        assert_eq!(merged.matches("<name>psx</name>").count(), 1);

        assert!(fix.apply("not xml at all", "desk").is_err());

        // Batocera doesn't run ES-DE: nothing to fix there.
        settings.nodes.get_mut("desk").unwrap().platform = "batocera".into();
        assert!(!esde_bin_fix(&settings, "desk").unwrap().is_needed());
    }
}
